package flaamingo.aprendendo.basic;

public class operadoresParte02 {
    /*
    * < menor que
    * > maior que
    * <= menor ou igual
    * >= maior ou igual
    * == igual
    * |= direrente de
     */



    public static void main(String[] args) {
        byte idadeMae = 42;
        byte idadePai = 60;
        byte idadeIrmaDaMae = 41;
        System.out.println(idadeMae < idadePai);
        System.out.println(idadeMae > idadePai);
        System.out.println(idadeMae == idadePai);
        System.out.println(idadeMae <= idadePai);
        System.out.println(idadeMae  >= idadeIrmaDaMae);


    }
}
